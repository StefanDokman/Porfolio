// Builds src/knowledge.generated.ts from knowledge/*.md.
//
// Each file can start with front-matter (title, optional link). The file is split at
// its "## " headings, and every section becomes one document the chat can cite.
// A section can name the portfolio location it belongs to with a comment such as
//   <!-- link: #neuroblast -->
// which the chat uses to link its "Sources" back to that part of the site.
// Files whose names start with "_" are drafts and are skipped.
//
// Runs automatically before `wrangler dev` and `wrangler deploy` (see wrangler.jsonc).

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const knowledgeDir = join(root, "knowledge");
const outFile = join(root, "src", "knowledge.generated.ts");

// Above this the whole-knowledge-in-every-request approach gets expensive;
// see docs/chat.md ("When the knowledge grows").
const WARN_TOKENS = 50_000;

function fail(message) {
  console.error(`build-knowledge: ${message}`);
  process.exit(1);
}

function parseFrontMatter(raw, file) {
  const text = raw.replace(/\r\n/g, "\n");
  if (!text.startsWith("---\n")) return { meta: {}, body: text };
  const end = text.indexOf("\n---", 4);
  if (end === -1) fail(`${file}: front-matter is missing its closing ---`);
  const meta = {};
  for (const line of text.slice(4, end).split("\n")) {
    const m = line.match(/^([A-Za-z_]+):\s*(.*)$/);
    if (m) meta[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
  }
  return { meta, body: text.slice(end + 4).replace(/^\n+/, "") };
}

function checkLink(link, file) {
  if (link == null || link === "") return null;
  if (/^#[\w-]+$/.test(link) || /^https:\/\/\S+$/.test(link)) return link;
  fail(`${file}: link "${link}" must be a page anchor like #neuroblast or an https:// URL`);
}

// "Neuroblast · Unity Developer · Aug 2025" -> "Neuroblast"; "Web Projects (PixiJS)" -> "Web Projects"
function shortLabel(heading) {
  return heading.split(/\s+·\s+|\s+\(/)[0].trim();
}

function linkComment(text) {
  const m = text.match(/<!--\s*link:\s*(\S+?)\s*-->/);
  return { link: m ? m[1] : null, text: text.replace(/[ \t]*<!--\s*link:[^>]*-->[ \t]*\n?/g, "") };
}

const files = readdirSync(knowledgeDir)
  .filter((f) => f.endsWith(".md") && !f.startsWith("_") && !f.startsWith("."))
  .sort();
if (files.length === 0) fail("knowledge/ has no .md files");

const docs = [];
for (const file of files) {
  const { meta, body } = parseFrontMatter(readFileSync(join(knowledgeDir, file), "utf8"), file);
  const fileTitle = meta.title || file.replace(/\.md$/, "");
  const fileLink = checkLink(meta.link, file);

  const parts = body.split(/^(?=## )/m);
  for (const part of parts) {
    const { link, text } = linkComment(part);
    const clean = text.trim();
    if (!clean) continue;
    const heading = clean.startsWith("## ") ? clean.slice(3, clean.indexOf("\n") === -1 ? undefined : clean.indexOf("\n")).trim() : null;
    // The part before the first "## " only counts if it has more than a "# Title" line.
    if (!heading && clean.split("\n").filter((l) => l.trim() && !l.startsWith("# ")).length === 0) continue;
    const title = heading ?? fileTitle;
    docs.push({
      title,
      label: heading ? shortLabel(heading) : fileTitle,
      link: checkLink(link, file) ?? fileLink,
      text: clean,
    });
  }
}

const chars = docs.reduce((n, d) => n + d.text.length, 0);
const approxTokens = Math.round(chars / 3.5);

const out = `// Generated by scripts/build-knowledge.mjs from knowledge/*.md. Do not edit.
export interface KnowledgeDoc {
  title: string;
  label: string;
  link: string | null;
  text: string;
}

export const KNOWLEDGE: KnowledgeDoc[] = ${JSON.stringify(docs, null, 2)};
`;
mkdirSync(join(root, "src"), { recursive: true });
writeFileSync(outFile, out);

console.log(
  `build-knowledge: ${files.length} file(s), ${docs.length} documents, ~${approxTokens.toLocaleString("en")} tokens`,
);
if (approxTokens > WARN_TOKENS) {
  console.warn(
    `build-knowledge: WARNING the knowledge is over ~${WARN_TOKENS.toLocaleString("en")} tokens; ` +
      "every chat message pays for it, see docs/chat.md",
  );
}
